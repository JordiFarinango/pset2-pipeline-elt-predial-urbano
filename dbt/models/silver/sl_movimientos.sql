    movimiento_id,
    obligacion_id,
    fecha_pago_declarada,
    importe_principal,
    importe_solares,
    importe_medicina,
    importe_educacion,
    importe_magisterio,
    importe_vivienda,
    importe_bomberos,
    importe_escolares,
    importe_procesamiento,
    importe_basura,
    importe_bordillo,
    importe_alcanta,
    importe_adoqui_nuevo,
    importe_ado_glob_2011,
    total_movimiento_declarado,
    recargo_declarado,
    descuento_declarado,
    interes_mora_declarado,
    costas_procesales_declaradas,
    saldo_declarado,
    fecha_emision_declarada,
    fecha_creacion_declarada,
    fecha_modificacion_declarada,
    fecha_anulacion_declarada,
    fecha_proceso_declarada,
    estado_codigo,
    condicion_codigo,
    tipo_movimiento_codigo,
    tipo_documento_codigo,
    lote_id,
    capturado_en,
    id_version,
    fecha_pago_declarada is null as dq_fecha_pago_nula,
    coalesce(fecha_pago_declarada < fecha_emision_declarada,false) as dq_pago_anterior_emision,
    coalesce(fecha_pago_declarada > to_date(convert_timezone('UTC',capturado_en)),false) as dq_pago_posterior_captura,
    fecha_proceso_declarada is null as dq_fecha_proceso_nula,
    total_movimiento_declarado is null as dq_total_nulo,
    coalesce(total_movimiento_declarado < 0,false) as dq_total_negativo,
    coalesce(estado_codigo='A' and fecha_anulacion_declarada is null,false) as dq_a_sin_fecha_anulacion,
    coalesce(estado_codigo='F' and fecha_anulacion_declarada is not null,false) as dq_f_con_fecha_anulacion
from {{ ref('br_movimientos') }}
where lote_id = {{ lote_id_sql() }}
