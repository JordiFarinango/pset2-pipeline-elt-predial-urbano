select
    obligacion_id,
    anio_fiscal,
    importe_principal,
    importe_solares,
    importe_medicina,
    importe_educacion,
    importe_magisterio,
    importe_vivienda,
    importe_bomberos,
    importe_escolares,
    importe_procesamiento,
    importe_basura,
    importe_bordillo,
    importe_alcanta,
    importe_adoqui_nuevo,
    importe_ado_glob_2011,
    total_obligacion_declarado,
    fecha_emision_declarada,
    fecha_creacion_declarada,
    fecha_modificacion_declarada,
    fecha_pago_actual_declarada,
    fecha_anulacion_declarada,
    estado_codigo,
    condicion_codigo,
    tipo_documento_codigo,
    lote_id,
    capturado_en,
    id_version,
    fecha_emision_declarada is null as dq_fecha_emision_nula,
    coalesce(fecha_emision_declarada < '1901-01-01'::date,false) as dq_emision_pre1901,
    coalesce(fecha_creacion_declarada > fecha_emision_declarada,false) as dq_creacion_posterior_emision,
    total_obligacion_declarado is null as dq_total_nulo,
    coalesce(total_obligacion_declarado < 0,false) as dq_total_negativo,
    coalesce(importe_principal < 0,false) as dq_principal_negativo,
    coalesce(fecha_pago_actual_declarada > to_date(convert_timezone('UTC',capturado_en)),false) as dq_pago_posterior_captura,
    coalesce(estado_codigo='A' and fecha_anulacion_declarada is null,false) as dq_a_sin_fecha_anulacion,
    coalesce(estado_codigo='F' and fecha_anulacion_declarada is not null,false) as dq_f_con_fecha_anulacion
from {{ ref('br_obligaciones') }}
where lote_id = {{ lote_id_sql() }}
