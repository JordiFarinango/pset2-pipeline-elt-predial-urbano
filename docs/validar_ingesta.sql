-- EJECUCION MANUAL de agregados, sin mostrar registros individuales.
-- Sustituir unicamente el UUID por el lote que disparo Kestra.
USE ROLE PSET2_PIPELINE_ROLE;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE PSET2_CAYAMBE;
USE SCHEMA RAW;
SET lote = '00000000-0000-0000-0000-000000000000';

SELECT LOTE_ID, COUNT(*) AS FILAS_LEDGER,
       MIN(OBLIGACIONES) AS OBLIGACIONES_ESPERADAS,
       MIN(MOVIMIENTOS) AS MOVIMIENTOS_ESPERADOS
FROM INGESTA_LOTES WHERE LOTE_ID=$lote GROUP BY LOTE_ID;

SELECT COUNT(*) AS OBLIGACIONES, COUNT(DISTINCT OBLIGACION_ID) AS IDS_UNICOS,
       COUNT_IF(OBLIGACION_ID IS NULL) AS IDS_NULOS
FROM RAW_URBANO_OBLIGACIONES WHERE LOTE_ID=$lote;

SELECT COUNT(*) AS MOVIMIENTOS, COUNT(DISTINCT MOVIMIENTO_ID) AS IDS_UNICOS,
       COUNT_IF(MOVIMIENTO_ID IS NULL OR OBLIGACION_ID IS NULL) AS IDS_NULOS
FROM RAW_URBANO_MOVIMIENTOS_PAGO WHERE LOTE_ID=$lote;

SELECT COUNT(*) AS MOVIMIENTOS_HUERFANOS
FROM RAW_URBANO_MOVIMIENTOS_PAGO p
WHERE p.LOTE_ID=$lote AND NOT EXISTS (
  SELECT 1 FROM RAW_URBANO_OBLIGACIONES u
  WHERE u.LOTE_ID=p.LOTE_ID AND u.OBLIGACION_ID=p.OBLIGACION_ID
);

SELECT COUNT(*) AS LOTES_DUPLICADOS FROM (
  SELECT LOTE_ID FROM INGESTA_LOTES GROUP BY LOTE_ID HAVING COUNT(*)>1
);
